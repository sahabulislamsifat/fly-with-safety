async (page) => {
  await page.setViewportSize({width:1440,height:900});
  const checks=[];
  const check=(name,passed)=>checks.push({name,passed});
  await page.goto('http://127.0.0.1:3100/contact');
  await page.getByRole('button',{name:/sign in/i}).first().waitFor();
  await page.setViewportSize({width:375,height:812});
  await page.getByRole('button',{name:'Open navigation menu'}).click();
  await page.getByRole('navigation',{name:'Mobile navigation'}).waitFor({state:'visible'});
  check('mobile navigation opens',await page.getByRole('navigation',{name:'Mobile navigation'}).isVisible());
  await page.keyboard.press('Escape');
  check('mobile navigation Escape closes',!await page.getByRole('navigation',{name:'Mobile navigation'}).isVisible());
  await page.setViewportSize({width:1440,height:900});
  await page.getByRole('button',{name:'More navigation options'}).click();
  await page.getByRole('menuitem',{name:'Contact Support',exact:true}).waitFor({state:'visible'});
  check('desktop More opens',await page.getByRole('menuitem',{name:'Contact Support',exact:true}).isVisible());
  await page.keyboard.press('Escape');
  await page.getByRole('button',{name:/sign in to your/i}).click();
  check('sign-in modal opens',await page.getByRole('dialog').isVisible());
  await page.keyboard.press('Escape');
  await page.getByRole('dialog').waitFor({state:'hidden'});
  check('sign-in Escape closes',await page.getByRole('dialog').count()===0);
  await page.getByRole('button',{name:'Send Message',exact:true}).click();
  check('empty contact form blocked',await page.getByLabel('First Name',{exact:true}).evaluate(el=>el.validity.valueMissing));
  await page.getByLabel('First Name',{exact:true}).fill('Audit');
  await page.getByLabel('Last Name',{exact:true}).fill('Fixture');
  await page.getByLabel('Email',{exact:true}).fill('audit@example.test');
  await page.getByLabel('Subject',{exact:true}).fill('Controlled UI test');
  await page.getByLabel('Message',{exact:true}).fill('Controlled browser fixture; no real submission.');
  const keys=[];
  let attempt=0;
  await page.route('**/api/v1/contact',async route=>{
    keys.push(route.request().headers()['idempotency-key']);
    attempt++;
    await route.fulfill({status:attempt===1?503:201,contentType:'application/json',body:JSON.stringify(attempt===1?{success:false,code:'AUDIT_FIXTURE',message:'Controlled failure'}:{success:true,data:{referenceNumber:'AUDIT-CONTACT-ONLY',status:'NEW',createdAt:new Date().toISOString()}})});
  });
  await page.getByRole('button',{name:'Send Message',exact:true}).click();
  await page.getByText('Controlled failure',{exact:true}).waitFor();
  check('server error does not show success',await page.getByText('Message Received!',{exact:true}).count()===0);
  await page.getByRole('button',{name:'Send Message',exact:true}).click();
  await page.getByText('AUDIT-CONTACT-ONLY',{exact:true}).waitFor();
  check('contact displays response reference',true);
  check('contact retry preserves idempotency key',!!keys[0]&&keys[0]===keys[1]);
  await page.unroute('**/api/v1/contact');
  await page.goto('http://127.0.0.1:3100/flights');
  await page.getByRole('button',{name:'Request specialist help instead'}).click();
  await page.getByRole('dialog').ariaSnapshot();
  await page.getByLabel('Full name',{exact:true}).fill('Audit Fixture');
  await page.getByLabel('Email',{exact:true}).fill('audit@example.test');
  await page.route('**/api/v1/flights/inquiries',route=>route.fulfill({status:201,contentType:'application/json',body:JSON.stringify({success:true,data:{referenceNumber:'AUDIT-INQUIRY-ONLY',inquiry:{},message:'Controlled fixture'}})}));
  await page.getByRole('button',{name:'Send flight request',exact:true}).click();
  await page.getByText('AUDIT-INQUIRY-ONLY',{exact:true}).waitFor();
  check('inquiry displays response reference',true);
  await page.unroute('**/api/v1/flights/inquiries');
  await page.goto('http://127.0.0.1:3100/flights/results?from=DAC&to=CXB&depart=2027-06-20&return=2027-06-22&tripType=roundTrip&adults=2&children=1&infants=1');
  await page.getByRole('button',{name:'Modify Search',exact:true}).click();
  await page.getByLabel('Departure Date',{exact:true}).fill('2027-07-01');
  await page.getByRole('button',{name:'Update Results',exact:true}).click();
  await page.waitForURL(/depart=2027-07-01/);
  const query=new URL(page.url()).searchParams;
  check('modify search preserves children and infants',query.get('children')==='1'&&query.get('infants')==='1');
  check('modify search adjusts round-trip return',query.get('return')==='2027-07-01');
  return {checks,failed:checks.filter(c=>!c.passed),note:'Success submissions use explicit intercepted fixtures; no persistence or email is verified.'};
}
