async (page) => {
  await page.setViewportSize({width:1440,height:900});
  const checks = [];
  const check = (name, passed, detail) => checks.push({ name, passed, detail });
  await page.goto('http://127.0.0.1:3100/flights');
  await page.getByRole('button', { name: /sign in/i }).first().waitFor();
  await page.setViewportSize({width:320,height:900});
  await page.locator('main').ariaSnapshot();
  await page.getByRole('button', {name:/^FROM Dhaka/}).click();
  check('airport popover fits 320px', await page.getByRole('listbox').evaluate(el => { const r=el.getBoundingClientRect();return r.left>=0&&r.right<=innerWidth; }));
  await page.getByLabel('Search FROM airport').press('Escape');
  await page.getByRole('button',{name:/PASSENGER & CLASS/}).click();
  const passengerDialog=page.getByRole('dialog',{name:'Select passengers and cabin class'});
  check('passenger popover fits 320px', await passengerDialog.evaluate(el=>{const r=el.getBoundingClientRect();return r.left>=0&&r.right<=innerWidth;}));
  await page.getByRole('button',{name:'Increase adult passengers'}).click();
  await page.getByRole('button',{name:'Increase infant passengers'}).click();
  await page.getByRole('button',{name:'Increase infant passengers'}).click();
  await page.getByRole('button',{name:'Decrease adult passengers'}).click();
  check('reducing adults clamps infants', await page.getByRole('button',{name:/PASSENGER & CLASS 2 Passengers/}).count()===1);
  await page.getByRole('button',{name:'Decrease adult passengers'}).press('Escape');
  check('passenger Escape closes', await passengerDialog.count()===0);
  await page.getByRole('button',{name:'Add preferred airline'}).click();
  check('airline popover fits 320px', await page.getByRole('dialog',{name:'Select preferred airlines'}).evaluate(el=>{const r=el.getBoundingClientRect();return r.left>=0&&r.right<=innerWidth;}));
  await page.getByRole('button',{name:'Close preferred airlines'}).click();
  await page.getByRole('button',{name:'Multi City',exact:true}).click();
  await page.locator('main').ariaSnapshot();
  await page.getByRole('button',{name:'Request itinerary',exact:true}).click();
  const inquiry=page.getByRole('dialog');
  check('multi-city retains every leg in notes', /DAC.*BKK.*BKK.*SIN/.test(await inquiry.getByRole('textbox',{name:/notes/i}).inputValue()));
  check('inquiry fits mobile viewport',await inquiry.evaluate(el=>{const r=el.getBoundingClientRect();return r.top>=0&&r.bottom<=innerHeight&&r.left>=0&&r.right<=innerWidth;}));
  await page.keyboard.press('Escape');
  check('inquiry Escape closes',await page.getByRole('dialog').count()===0);
  await page.goto('http://127.0.0.1:3100/flights/results?from=DAC&to=CXB&depart=2027-06-20&tripType=oneWay&cabin=premiumEconomy');
  await page.getByRole('button',{name:'Book with Agent'}).first().waitFor();
  const resultText=await page.locator('main').innerText();
  check('premium economy returns offers',!resultText.includes('Search Failed'));
  check('flight results no zero fares', !/\n0 BDT\n/.test(resultText));
  check('demo clearly labeled', resultText.includes('DEMO MODE'));
  await page.getByRole('button',{name:'Book with Agent'}).first().click();
  await page.getByRole('dialog').ariaSnapshot();
  check('booking modal visible',await page.getByRole('dialog').isVisible());
  await page.keyboard.press('Escape');
  check('booking modal Escape closes', await page.getByRole('dialog').count()===0);
  return {checks,failed:checks.filter(check=>!check.passed)};
}
